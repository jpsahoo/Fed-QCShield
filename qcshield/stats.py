"""Multi-seed aggregation and significance testing (Reviewer 4 §6).

The original fixed ``random_state = 42`` everywhere and reported a single run
per configuration, so nothing in the paper distinguished a real improvement from
seed noise.  This module aggregates the per-seed result JSONs written by
``cli.run`` into mean +/- std, and runs Wilcoxon signed-rank tests of the
headline configuration against every baseline over the paired seeds.

Wilcoxon is the right test here: the same seeds are used for every model, so the
samples are paired, and with 5 seeds no normality assumption is defensible.
Note that with n=5 the smallest attainable two-sided p-value is 0.0625, so a
result can be *consistent* (5/5 seeds favouring one model) without reaching
p<0.05 -- the table reports both the p-value and the win count so the reader can
see that, rather than the p-value alone implying "no difference".
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np
import pandas as pd
from scipy.stats import wilcoxon

logger = logging.getLogger(__name__)

METRICS = ("accuracy", "f1_macro", "f1_weighted", "precision_macro",
           "recall_macro", "roc_auc_ovr")

#: The configuration the paper headlines.
HEADLINE = "QE_QCSL"


def load_records(results_dir: Path, dataset: Optional[str] = None) -> pd.DataFrame:
    """Flatten every result JSON into one row per (model, seed)."""
    rows = []
    for fp in sorted(Path(results_dir).glob("*.json")):
        try:
            r = json.loads(fp.read_text())
        except json.JSONDecodeError:
            logger.warning("skipping unreadable %s", fp.name)
            continue
        if "test" not in r:
            continue
        if dataset and r.get("dataset") != dataset:
            continue
        row = {"dataset": r["dataset"], "model": r["model"], "seed": r["seed"],
               "epochs": r.get("epochs"),
               "params": r.get("params", {}).get("total"),
               "quantum_params": r.get("params", {}).get("quantum"),
               "train_seconds": r.get("train_seconds")}
        row.update({m: r["test"].get(m) for m in METRICS})
        rows.append(row)
    return pd.DataFrame(rows)


def aggregate(results_dir: Path, dataset: Optional[str] = None) -> pd.DataFrame:
    """Mean +/- std per model, with Wilcoxon vs :data:`HEADLINE`."""
    df = load_records(results_dir, dataset)
    if df.empty:
        return df

    agg = (df.groupby("model")
             .agg(n_seeds=("seed", "nunique"),
                  params=("params", "first"),
                  quantum_params=("quantum_params", "first"),
                  train_seconds=("train_seconds", "mean"),
                  **{f"{m}_{s}": (m, s) for m in METRICS for s in ("mean", "std")})
             .reset_index())

    # paired Wilcoxon on f1_macro against the headline configuration
    piv = df.pivot_table(index="seed", columns="model", values="f1_macro")
    pvals, wins = {}, {}
    if HEADLINE in piv.columns:
        for model in piv.columns:
            if model == HEADLINE:
                pvals[model], wins[model] = np.nan, ""
                continue
            pair = piv[[HEADLINE, model]].dropna()
            if len(pair) < 3 or np.allclose(pair[HEADLINE], pair[model]):
                pvals[model], wins[model] = np.nan, ""
                continue
            try:
                pvals[model] = float(wilcoxon(pair[HEADLINE], pair[model])[1])
            except ValueError:
                pvals[model] = np.nan
            wins[model] = f"{int((pair[HEADLINE] > pair[model]).sum())}/{len(pair)}"
    agg["wilcoxon_p_vs_headline"] = agg["model"].map(pvals)
    agg["headline_wins"] = agg["model"].map(wins)
    return agg.sort_values("f1_macro_mean", ascending=False).reset_index(drop=True)


def format_pm(mean: float, std: float, places: int = 4) -> str:
    if mean is None or (isinstance(mean, float) and np.isnan(mean)):
        return "--"
    if std is None or (isinstance(std, float) and np.isnan(std)):
        return f"{mean:.{places}f}"
    return f"{mean:.{places}f} $\\pm$ {std:.{places}f}"


def write_latex_table(agg: pd.DataFrame, out: Path, dataset: str) -> Path:
    """Emit a drop-in LaTeX fragment for the regenerated Table 3."""
    lines = [
        "% Auto-generated by qcshield.stats -- do not edit by hand.",
        f"% Dataset: {dataset}.  Mean $\\pm$ std over "
        f"{int(agg['n_seeds'].max())} seeds.",
        "\\begin{table}[htbp]", "\\centering",
        f"\\caption{{Performance on {dataset}, mean $\\pm$ standard deviation over "
        f"{int(agg['n_seeds'].max())} random seeds. $p$ from a Wilcoxon "
        f"signed-rank test of {HEADLINE.replace('_', '-')} against each row over "
        "the paired seeds; `wins' counts the seeds on which "
        f"{HEADLINE.replace('_', '-')} scored higher.}}",
        f"\\label{{tab:results_{dataset.replace('-', '_')}}}",
        "\\begin{tabular}{lrrrrr}", "\\toprule",
        "Model & Accuracy & Macro-F1 & Weighted-F1 & $p$ & Wins \\\\",
        "\\midrule",
    ]
    for _, r in agg.iterrows():
        p = r["wilcoxon_p_vs_headline"]
        pstr = "--" if p is None or (isinstance(p, float) and np.isnan(p)) else f"{p:.4f}"
        name = str(r["model"]).replace("_", "-")
        if name == HEADLINE.replace("_", "-"):
            name = f"\\textbf{{{name}}}"
        lines.append(
            f"{name} & {format_pm(r['accuracy_mean'], r['accuracy_std'])} & "
            f"{format_pm(r['f1_macro_mean'], r['f1_macro_std'])} & "
            f"{format_pm(r['f1_weighted_mean'], r['f1_weighted_std'])} & "
            f"{pstr} & {r['headline_wins'] or '--'} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    logger.info("wrote %s", out)
    return out
